"""The bundled 200-document toy set behind `measurerag smoke`.

Synthetic, offline, no licence encumbrance. It exists so that a newcomer can
clone the repo on a machine with no network and still see a real budget table
inside three minutes.
"""

from __future__ import annotations

from pathlib import Path

from .base import Dataset, Doc, read_jsonl

FIXTURES = Path(__file__).resolve().parents[3] / "fixtures" / "toy"


def load(cache_dir=None, language: str | None = None, **_) -> Dataset:
    docs = [
        Doc(doc_id=r["doc_id"], text=r["text"], title=r.get("title", ""))
        for r in read_jsonl(FIXTURES / "corpus.jsonl")
        if language in (None, "all") or r.get("lang") == language
    ]
    keep = {d.doc_id for d in docs}

    queries: dict[str, str] = {}
    answers: dict[str, list[str]] = {}
    for r in read_jsonl(FIXTURES / "queries.jsonl"):
        if language not in (None, "all") and r.get("lang") != language:
            continue
        queries[r["query_id"]] = r["text"]
        if r.get("answers"):
            answers[r["query_id"]] = list(r["answers"])

    qrels: dict[str, dict[str, int]] = {}
    with open(FIXTURES / "qrels.tsv", encoding="utf-8") as fh:
        next(fh)
        for line in fh:
            qid, did, rel = line.rstrip("\n").split("\t")
            if qid in queries and did in keep:
                qrels.setdefault(qid, {})[did] = int(rel)

    return Dataset(
        name="toy" if language in (None, "all") else f"toy-{language}",
        language=language or "mixed",
        docs=docs,
        queries=queries,
        qrels=qrels,
        answers=answers,
        license="Apache-2.0 (synthetic, generated by scripts/make_fixtures.py)",
        source="bundled fixture",
        notes=["Synthetic smoke-test fixture. Numbers from it mean nothing about real corpora."],
    )
